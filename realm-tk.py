#!/usr/bin/env -S python3 -OO
# -*- coding = utf-8 -*-
"""
Realm changing module for World of Warcraft,
using tkinter
"""
import sys
import tkinter as tk

##  MAIN ENTRY POINT
def main(args=None):
    root = tk.Tk()
    root.mainloop()
    return 0

if __name__ == '__main__':
    sys.exit(main(sys.argv))
